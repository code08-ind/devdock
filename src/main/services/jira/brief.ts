import type { JiraIssueDetail } from '@shared/jira'
import type { Agent } from '@shared/startwork'
import { acceptanceSection, withoutAcceptanceSection } from './model'

/**
 * The Start-work ticket brief, agent choice and ready message (SPEC 6.5 steps 3–5). Pure.
 */

/** Repo-relative brief path (always `/`, also on Windows: it goes into the agent message). */
export const briefRelativePath = (key: string) => `docs/ai/specs/${key}/TICKET.md`

export interface Classification {
  agent: Agent
  reason: string
}

/**
 * SPEC 6.5 step 4: Bug → bug-fixer; Story/Task (incl. Sub-task) whose acceptance criteria are
 * missing or too thin → spec-writer; everything else → feature-builder.
 */
export function classify(issue: JiraIssueDetail): Classification {
  if (/\b(bug|defect)\b/i.test(issue.type)) return { agent: 'bug-fixer', reason: issue.type }
  const unclear = /story|task/i.test(issue.type) ? unclearCriteria(issue.acceptanceCriteria) : null
  if (unclear) return { agent: 'spec-writer', reason: `${issue.type} with ${unclear}` }
  return {
    agent: 'feature-builder',
    reason: /story|task/i.test(issue.type) ? `${issue.type} with acceptance criteria` : issue.type,
  }
}

/** Why the criteria are unclear, or null when they're usable. */
function unclearCriteria(ac: string | null): string | null {
  if (ac === null || !ac.trim()) return 'no acceptance criteria'
  const plain = ac
    .replace(/[#>*_`~[\]()-]|^\s*\d+\.\s/gm, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  if (/^(tbd|tba|todo|n\/?a|none|\?+)\.?$/i.test(plain)) return 'placeholder acceptance criteria'
  // Fewer than ~3 words can't describe a testable outcome.
  if (plain.split(' ').filter((w) => /\w/.test(w)).length < 3) return 'unclear acceptance criteria'
  return null
}

/** Use the <agent> agent. Ticket brief: <path>. Figma: <first Figma link>. */
export function agentMessage(agent: Agent, briefRef: string, issue: JiraIssueDetail): string {
  const figma = issue.links.find((l) => l.kind === 'figma')
  return [`Use the ${agent} agent.`, `Ticket brief: ${briefRef}.`, figma && `Figma: ${figma.url}.`]
    .filter(Boolean)
    .join(' ')
}

/** TICKET.md: summary, description, acceptance criteria, links, last 10 comments. */
export function buildBrief(issue: JiraIssueDetail, generatedAt: Date): string {
  // Criteria taken from the description are shown once, in their own section.
  const fromDescription =
    issue.acceptanceCriteria !== null &&
    acceptanceSection(issue.description) === issue.acceptanceCriteria
  const description = fromDescription
    ? withoutAcceptanceSection(issue.description)
    : issue.description

  const meta = [
    ['Type', issue.type],
    ['Priority', issue.priority],
    ['Status', issue.status],
    ['Sprint', issue.sprint],
    ['Fix version', issue.fixVersions.join(', ') || null],
    ['Jira', issue.url],
  ]
    .filter((row): row is [string, string] => Boolean(row[1]))
    .map(([k, v]) => `- **${k}:** ${v}`)

  const links = issue.links.length
    ? issue.links.map((l) => `- ${l.kind === 'figma' ? 'Figma' : 'Confluence'}: ${l.url}`)
    : ['_None found in the description._']

  const comments = issue.comments.length
    ? issue.comments.flatMap((c) => [
        `### ${c.author} — ${c.created.slice(0, 10) || 'unknown date'}`,
        '',
        demoteHeadings(c.body, 3) || '_(empty)_',
        '',
      ])
    : ['_No comments._', '']

  return [
    `# ${issue.key}: ${issue.summary}`,
    '',
    ...meta,
    '',
    '## Summary',
    '',
    issue.summary,
    '',
    '## Description',
    '',
    demoteHeadings(description, 2) || '_No description._',
    '',
    '## Acceptance criteria',
    '',
    issue.acceptanceCriteria
      ? demoteHeadings(issue.acceptanceCriteria, 2)
      : '_None in the ticket. Clarify them before building._',
    '',
    '## Links',
    '',
    ...links,
    '',
    issue.comments.length ? `## Comments (last ${issue.comments.length})` : '## Comments',
    '',
    ...comments,
    '---',
    '',
    `_Generated by DevDock from ${issue.url} on ${generatedAt.toISOString().slice(0, 10)}. Ticket content is copied as-is; regenerate rather than edit._`,
    '',
  ].join('\n')
}

/** Pushes Markdown headings down `by` levels (max h6) so they nest under the brief's sections. */
export function demoteHeadings(markdown: string, by: number): string {
  let fence: string | null = null
  return markdown
    .split('\n')
    .map((line) => {
      const f = /^\s*(```|~~~)/.exec(line)
      if (f) fence = fence === f[1] ? null : (fence ?? f[1]!)
      if (fence) return line
      return line.replace(
        /^(#{1,6})(\s)/,
        (_, hashes: string, sp: string) => `${'#'.repeat(Math.min(6, hashes.length + by))}${sp}`,
      )
    })
    .join('\n')
    .trim()
}
